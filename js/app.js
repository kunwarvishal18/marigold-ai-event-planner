export function createTemplate() {
  const b = readForm(); if (!validateBrief(b, false)) return;
  const p = buildPlan(b, templateData(b.type), "template");
  logEntryFor(p, "Created from the standard template", "template");
  openPlan(p); savePlan(); $("#formHint").textContent = "Template plan created. It isn't AI generated; use Fresh AI plan to personalise it.";
}
export function logEntryFor(p, text, origin) { p.log.unshift({ text, origin, at: Date.now() }); }
export async function generate(fresh) {
  if (S.busy.gen) return;
  const b = readForm(); if (!validateBrief(b, S.mode === "edit")) return;
  if (!aiOn()) { createTemplate(); return; }
  const seq = S.seq.gen = (S.seq.gen || 0) + 1; S.busy.gen = true; S.ctl.gen = new AbortController();
  const hint = $("#formHint"); const t0 = Date.now();
  // The message is announced once; only the aria-hidden seconds counter changes, so screen readers aren't interrupted every second.
  hint.innerHTML = `<span class="progress"><span class="spinner"></span>Claude is drafting your plan<span aria-hidden="true"> (<span id="genSecs">0</span>s)</span>. This usually takes 20–90 seconds.</span>`;
  const tick = () => { const el = $("#genSecs"); if (el) el.textContent = Math.round((Date.now() - t0) / 1000); };
  const timer = setInterval(tick, 1000); renderForm();
  try {
    const ev = parseISO(b.date); const dl = ev ? daysBetween(today(), ev) : null;
    const data = await aiJSON(genPrompt(b), (o, ctx) => validateGen(o, dl, ctx), { signal: S.ctl.gen.signal, tier: "default" });
    if (seq !== S.seq.gen) return;
    const p = buildPlan(b, data, "ai");
    logEntryFor(p, fresh ? "Generated a fresh AI plan" : "Generated by Claude", "ai");
    if (data.unknownDepsRemoved) logEntryFor(p, `Removed ${data.unknownDepsRemoved} task link${data.unknownDepsRemoved > 1 ? "s" : ""} to tasks that don't exist in Claude's plan`, "rule");
    if (data.cyclesRemoved) logEntryFor(p, `Removed ${data.cyclesRemoved} circular task dependenc${data.cyclesRemoved > 1 ? "ies" : "y"} from Claude's plan`, "rule");
    openPlan(p); savePlan(); S.tab = "overview"; renderAll();
    hint.textContent = "AI plan ready and saved in this browser.";
    toast("Your AI plan is ready.");
  } catch (e) {
    if (seq !== S.seq.gen) return;
    hint.innerHTML = `<span class="field-err" role="alert" style="margin:0">${esc(aiErrMsg(e))}</span>`;
    if (e.code !== "cancelled") { const r = document.createElement("div"); r.className = "btnrow"; r.innerHTML = '<button type="button" class="btn small" id="retryGen">Retry</button><button type="button" class="btn ghost small" id="tplInstead">Use template instead</button>'; hint.append(r); $("#retryGen").onclick = () => generate(fresh); $("#tplInstead").onclick = createTemplate; }
  } finally { clearInterval(timer); if (seq === S.seq.gen) { S.busy.gen = false; renderForm(); } }
}
export function reviewDetails() {
  const b = readForm(); if (!validateBrief(b, true)) return;
  const cur = S.plan.brief; const ch = {};
  for (const k of ["name", "date", "time", "guests", "venueCapacity", "budget", "city", "style", "notes", "type", "currency"]) if ((b[k] ?? "") !== (cur[k] ?? "")) ch[k] = b[k];
  if (!Object.keys(ch).length) { $("#formHint").textContent = "No changes to review."; return; }
  const pr = makeProposal({ origin: "rule", kind: "details", title: "Update event details", explanation: ch.budget != null ? "The new total is spread across categories in proportion, never below committed spend. Ask the co-planner if you want a smarter rebalance." : "Timeline dates recalculate from the event date.", changes: { brief: ch } });
  showProposal(pr);
}
export async function optimize(pct) {
  if (S.busy.opt) return;
  const p = S.plan, b = p.brief, total = b.budget; const target = Math.round(total * (1 - pct / 100)); const committed = sum(p.budget.map(l => l.committed || 0));
  const err = $("#optErr");
  if (target < committed) { err.textContent = `Saving ${pct}% would put the budget (${money(target)}) below what's already committed (${money(committed)}).`; err.hidden = false; return; }
  const protect = clip(S.protect, 120);
  if (!aiOn()) {
    const lines = p.budget.map(l => ({ category: l.category, amount: l.amount }));
    showProposal(makeProposal({ origin: "rule", kind: "optimize", title: `Save ${pct}% (rule-based)`, explanation: `Claude isn't available, so every category is cut in proportion to its uncommitted amount. New total ${money(target)}, saving ${money(total - target)}.`, tradeoffs: ["A proportional cut doesn't consider which areas matter most to you."], changes: { brief: { budget: target }, budget: lines.map(l => ({ ...l })) } }));
    return;
  }
  const seq = S.seq.opt = (S.seq.opt || 0) + 1; const planId = p.id; S.busy.opt = true; renderBudget(analyze(p));
  try {
    const out = await aiJSON(`You are a budget optimizer for an event plan. Reduce the total planned spend by ${pct}%: from ${total} to exactly ${target} ${b.currency} (saving ${total - target}).

${planContext(p)}

Constraints:
- Return the full new allocation. Whole numbers that add up to EXACTLY ${target}.
- No category may go below its committed amount. Keep every category that has committed spend.
- Keep a Contingency line of at least 3% of the new total.
- ${protect ? `Protect what the user lists here; cut these least or not at all: ${fence("user_note", protect)}` : "Protect what the brief's priorities say matters most."}
- ${SAFETY}
- Prefer smart substitutions (digital invites, seasonal flowers, reuse décor across functions) over across-the-board cuts.

Return ONLY JSON: {"explanation": "where the savings come from and why, 2-3 sentences", "tradeoffs": ["what the person gives up"], "budget": [{"category": "string", "amount": number, "note": "what changes in this category"}]}`, validateBudgetOpt, { tier: "default" });
    if (seq !== S.seq.opt || !S.plan || S.plan.id !== planId) return;
    showProposal(makeProposal({ origin: "ai", kind: "optimize", title: `Save ${pct}%: ${money(total - target)}`, explanation: out.explanation, tradeoffs: out.tradeoffs, changes: { brief: { budget: target }, budget: out.budget } }));
  } catch (e) { if (seq === S.seq.opt) toast(aiErrMsg(e), true); }
  finally { if (seq === S.seq.opt) { S.busy.opt = false; if (S.plan) renderBudget(analyze(S.plan)); } }
}
export async function moreIdeas() {
  if (S.busy.ideas || !aiOn()) return;
  const p = S.plan, planId = p.id; const seq = S.seq.ideas = (S.seq.ideas || 0) + 1; S.busy.ideas = true; renderIdeas();
  try {
    const focus = clip(S.ideaFocus, 120);
    const out = await aiJSON(`Suggest 4 NEW creative, specific ideas for this event. Tie them to the city's regional customs, the theme, the budget level, the guest profile and any accessibility or sustainability needs.${focus ? ` Focus on what the user asks for here: ${fence("user_note", focus)}` : ""}
Do not repeat or lightly reword these existing ideas: ${fence("plan_data", p.ideas.map(i => i.title).join("; ") || "none")}

${fence("event_brief", briefText(p.brief))}

${SAFETY}
Return ONLY a JSON array: [{"title": "string", "detail": "1-2 sentences", "tag": "one word", "costLow": number, "costHigh": number}] with costs in ${p.brief.currency}.`, o => {
      const errs = []; if (!Array.isArray(o)) return { ok: false, errors: ["Top level must be an array"] };
      const v = o.slice(0, 6).map((x, i) => validIdea(x, errs, `[${i}]`)); return errs.length || !v.length ? { ok: false, errors: errs.length ? errs : ["empty array"] } : { ok: true, value: v };
    }, { tier: "default" });
    if (seq !== S.seq.ideas || !S.plan || S.plan.id !== planId) return;
    const fresh = out.filter(i => !S.plan.ideas.some(x => norm(x.title) === norm(i.title)));
    if (!fresh.length) { toast("Claude only suggested ideas you already have. Try a different focus."); return; }
    commit(`Added ${fresh.length} AI ideas`, pl => fresh.forEach(i => pl.ideas.push({ id: uid(), ...i, origin: "ai" })), { structural: false });
    toast(`${fresh.length} new idea${fresh.length > 1 ? "s" : ""} added.`);
  } catch (e) { if (seq === S.seq.ideas) { const el = $("#ideaErr"); if (el) { el.textContent = aiErrMsg(e); el.hidden = false; } } }
  finally { if (seq === S.seq.ideas) { S.busy.ideas = false; if (S.plan) renderIdeas(); } }
}
export async function aiRiskReview() {
  if (S.busy.risks || !aiOn()) return;
  const p = S.plan, planId = p.id, rev = p.rev; const seq = S.seq.risks = (S.seq.risks || 0) + 1; S.busy.risks = true; renderOverview(analyze(p));
  try {
    const out = await aiJSON(`Review this event plan for contextual risks that simple rules can't see: season and climate for the city and date, local logistics and permissions, cultural timing, guest needs (elderly, children, dietary, accessibility), vendor lead times in that market, and whether the budget per guest is realistic for the location. Don't repeat the rule-based risks already listed.

${planContext(p)}

${SAFETY}
Return ONLY JSON: {"risks": [{"severity": "critical"|"high"|"medium"|"low", "title": "string", "why": "1-2 sentences", "action": "one concrete step"}]} with 3-6 risks.`, o => { const r = validRisks(o && o.risks); return r.length ? { ok: true, value: r } : { ok: false, errors: ['"risks" must be a non-empty array of {severity,title,why,action}'] }; }, { tier: "default" });
    if (seq !== S.seq.risks || !S.plan || S.plan.id !== planId) return;
    S.plan.aiRisks = { at: Date.now(), rev, items: out }; savePlan();
  } catch (e) { if (seq === S.seq.risks) toast(aiErrMsg(e), true); }
  finally { if (seq === S.seq.risks) { S.busy.risks = false; if (S.plan) renderOverview(analyze(S.plan)); } }
}
export async function sendChat(text) {
  text = clip(text, 1200); if (!text || S.busy.chat) return;
  if (!aiOn()) { toast("The co-planner needs Claude.", true); return; }
  const p = S.plan, planId = p.id; const seq = S.seq.chat = (S.seq.chat || 0) + 1;
  const prompt = chatPrompt(p, text);
  p.chat.push({ role: "user", text, at: Date.now() }); p.chat = p.chat.slice(-60); $("#askInput").value = "";
  S.busy.chat = true; S.ctl.chat = new AbortController(); savePlan(); renderChat();
  let pr = null;
  try {
    const out = await aiJSON(prompt, validateChat, { signal: S.ctl.chat.signal, tier: "default" });
    if (seq !== S.seq.chat || !S.plan || S.plan.id !== planId) return;
    S.plan.chat.push({ role: "assistant", text: out.reply, at: Date.now() });
    if (out.proposal) {
      pr = makeProposal({ origin: "ai", kind: "chat", title: out.proposal.title, explanation: out.proposal.explanation, tradeoffs: out.proposal.tradeoffs, changes: out.proposal.changes, request: text });
      if (pr.diff.empty && !pr.blocked) { S.plan.chat.push({ role: "note", text: "Claude suggested a change, but it wouldn't alter the plan." }); pr = null; }
      else S.plan.chat.push({ role: "note", text: `Proposal ready: “${pr.title}”. Review it above the tabs.`, at: Date.now() });
    }
  } catch (e) {
    if (seq === S.seq.chat && S.plan && S.plan.id === planId) S.plan.chat.push({ role: "error", text: aiErrMsg(e), at: Date.now() });
  } finally {
    if (seq === S.seq.chat) { S.busy.chat = false; if (S.plan) { savePlan(); renderAll(); if (pr) showProposal(pr); } }
  }
}

export function openSample() {
  const b = scenBrief(SCEN[0]);
  const p = buildPlan(b, templateData("Wedding"), "example", iso(addDays(today(), -45)));
  p.summary = "Example data built from Marigold's wedding template so you can explore the app. It isn't AI generated. Generate with AI in Event details to get a plan written for this brief.";
  p.budget.find(l => /venue/i.test(l.category)).committed = 450000;
  p.budget.find(l => /photo/i.test(l.category)).committed = 230000;
  const vv = p.vendors.find(v => /venue/i.test(v.category)); Object.assign(vv, { status: "Booked", payment: "Deposit paid", name: "Example venue (placeholder)", quote: 450000, arrival: "08:00" });
  const ph = p.vendors.find(v => /photo/i.test(v.category)); Object.assign(ph, { status: "Negotiating", quote: 230000, options: [{ id: uid(), name: "Option A (placeholder)", contact: "", quote: 230000, notes: "Two shooters, drone" }, { id: uid(), name: "Option B (placeholder)", contact: "", quote: 185000, notes: "One shooter, 8 weeks delivery" }] });
  const sc = schedule(p); p.tasks.forEach(t => { if (sc.due[t.id] && sc.due[t.id] < addDays(today(), -10) && t.priority === "high") t.done = true; });
  p.log.unshift({ text: "Opened the sample wedding (template data)", origin: "template", at: Date.now() });
  openPlan(p); savePlan();
}

